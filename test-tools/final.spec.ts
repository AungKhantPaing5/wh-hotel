import { test, expect } from '@playwright/test';
test('customer request → owner approval → simulated payment in separate browser sessions', async ({browser})=>{
 const customer=await browser.newContext(),owner=await browser.newContext();
 const page=await customer.newPage(),admin=await owner.newPage();
 await page.goto('/');await expect(page.getByText('LOCAL TEST ONLY',{exact:false})).toBeVisible();
 await page.getByRole('button',{name:'My account',exact:true}).click();
 await page.getByLabel('Login email',{exact:true}).fill('guest@wh.test');
 await page.getByLabel('Login password',{exact:true}).fill('WhTestOnly2026!');
 await page.getByRole('button',{name:'Email sign in',exact:true}).click();
 await expect(page.getByText('Phone verified.',{exact:false})).toBeVisible();
 const checkIn=new Date(Date.now()+8*86400000).toISOString().slice(0,10),checkOut=new Date(Date.now()+9*86400000).toISOString().slice(0,10);
 await page.getByLabel('Check-in',{exact:true}).fill(checkIn);await page.getByLabel('Check-out',{exact:true}).fill(checkOut);
 await page.getByRole('button',{name:'Check availability',exact:true}).click();
 await expect(page.getByRole('status')).not.toContainText('error');
 await page.getByRole('button',{name:'Request stay',exact:true}).first().click();
 await expect(page.getByRole('status')).toContainText('PENDING_APPROVAL');
 await admin.goto('/admin');await admin.getByLabel('Admin email').fill('admin@wh.test');await admin.getByLabel('Admin password').fill('WhTestOnly2026!');
 await admin.getByRole('button',{name:'Email sign in',exact:true}).click();
 await expect(admin.getByRole('button',{name:'accept',exact:true})).toBeVisible();
 await admin.getByRole('button',{name:'accept',exact:true}).click();
 await expect(admin.getByText('AWAITING_PAYMENT',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Refresh profile',exact:true}).click();
 await page.getByRole('button',{name:'Simulate payment — no money',exact:true}).click();
 await expect(page.getByText('CONFIRMED',{exact:true})).toBeVisible();
 await admin.getByRole('button',{name:'Load / refresh dashboard',exact:true}).click();
 await admin.getByRole('button',{name:'Payments',exact:true}).click();
 await expect(admin.getByText(/SIMULATED ·/)).toBeVisible();
 await customer.close();await owner.close();
});
